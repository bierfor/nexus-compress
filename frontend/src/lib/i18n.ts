export type TranslationKey = keyof typeof ES;
export type Translations = Record<TranslationKey, string>;

const DICTIONARIES: Record<Locale, Translations> = {
  es: ES as unknown as Translations,
  en: EN as unknown as Translations,
  it: IT as unknown as Translations,
};

// ─────────────────────────────────────────────────────────────
//  Storage
// ─────────────────────────────────────────────────────────────

const LOCALE_KEY = "nexus-locale";

export function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "es";
  try {
    const stored = localStorage.getItem(LOCALE_KEY);
    if (stored === "es" || stored === "en" || stored === "it") return stored;
  } catch {}
  // Auto-detect from browser
  const lang = navigator.language.slice(0, 2).toLowerCase();
  if (lang === "en") return "en";
  if (lang === "it") return "it";
  return "es";
}

export function storeLocale(locale: Locale) {
  if (typeof window === "undefined") return;
  try { localStorage.setItem(LOCALE_KEY, locale); } catch {}
}

// ─────────────────────────────────────────────────────────────
//  translate helper
// ─────────────────────────────────────────────────────────────

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = DICTIONARIES[locale];
  let str: string = dict[key] ?? ES[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}
